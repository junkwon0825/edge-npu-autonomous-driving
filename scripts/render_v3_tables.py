"""Render reports/scenario_tables_v3.md from reports/evidence/scenarios_v3.json (no hand-edited numbers).

python scripts/render_v3_tables.py
"""

from __future__ import annotations

import json
from collections import defaultdict

import numpy as np

from npu_ad.config import resolve

MODES = [("gt_oracle", "GT oracle"), ("gt_gated", "GT-assisted"), ("mono", "perception-driven")]
CONDS = ["aeb_off", "ideal_0ms", "npu_p95", "gpu_p95", "stress_100ms", "npu_remote_p95", "stress_200ms"]


def f(v, nd=2):
    return "—" if v is None else (f"{v:.{nd}f}" if isinstance(v, float) else str(v))


def _strip(lines: list[str]) -> list[dict]:
    """Log rows without fields that legitimately differ between identical runs."""
    return [{k: v for k, v in json.loads(x).items() if k not in ("frame", "infer_e2e_ms")} for x in lines]


def cell(r: dict) -> str:
    if r is None:
        return ""
    if r["collision"]:
        return "**COLLISION**"
    if r["hazard"]:
        return f"{f(r['min_gap_m'])} m"
    return f"FP brakes: {r['false_positive_brake_events']}"


def main() -> int:
    runs = json.loads(resolve("reports/evidence/scenarios_v3.json").read_text(encoding="utf-8"))["runs"]
    base = [r for r in runs if not r.get("tag")]
    by = {(r["scenario"], r["mode"], r["ego_kmh"], r["condition"]): r for r in base}
    scen = list(dict.fromkeys(r["scenario"] for r in base))
    conds = [c for c in CONDS if any(r["condition"] == c for r in base)]
    out = [
        "# Scenario results v3 (generated by scripts/render_v3_tables.py)",
        "",
        "Source: `reports/evidence/scenarios_v3.json`. AEB v2, dt 0.01 s, 1 s settle phase, ego 30 km/h unless",
        "noted. Cells: minimum bumper gap before stop (hazard scenarios) or number of brake onsets",
        "(no-hazard scenarios = false-positive brake events). *GT-assisted* uses CARLA ground-truth range",
        "and TTC gated by detection; *perception-driven* uses only camera detections (flat-ground range).",
        "",
        "## Safety matrix, 30 km/h",
        "",
    ]
    for mode, label in MODES:
        out += [
            f"### {label} (`{mode}`)",
            "",
            "| scenario | " + " | ".join(conds) + " |",
            "|---|" + "---|" * len(conds),
        ]
        for s in scen:
            cells = []
            for c in conds:
                r = by.get((s, mode, 30.0, c)) or (by.get((s, "gt_oracle", 30.0, c)) if c == "aeb_off" else None)
                cells.append(cell(r))
            out.append(f"| {s} | " + " | ".join(cells) + " |")
        out.append("")
    # summary per mode
    out += [
        "## Summary per AEB input mode (30 km/h, AEB on, all latency conditions)",
        "",
        "| mode | hazard runs | collisions | min gap median (m) | FP brake events (no-hazard runs) | "
        "GT TTC at first brake, median (s) | in-path detection miss ratio, mean |",
        "|---|---|---|---|---|---|---|",
    ]
    for mode, label in MODES:
        rs = [r for r in base if r["mode"] == mode and r["ego_kmh"] == 30.0 and r["condition"] != "aeb_off"]
        hz = [r for r in rs if r["hazard"]]
        nh = [r for r in rs if not r["hazard"]]
        gaps = [r["min_gap_m"] for r in hz if r["min_gap_m"] is not None and not r["collision"]]
        ttc = [r["gt_ttc_at_first_brake_s"] for r in hz if r["gt_ttc_at_first_brake_s"] is not None]
        miss = [r["in_path_missed_ratio"] for r in hz if r["in_path_missed_ratio"] is not None]
        gap_med = f(float(np.median(gaps)) if gaps else None)
        out.append(
            f"| {label} | {len(hz)} | {sum(r['collision'] for r in hz)} | {gap_med} | "
            f"{sum(r['false_positive_brake_events'] or 0 for r in nh)} in {len(nh)} runs | "
            f"{f(float(np.median(ttc)) if ttc else None)} | {f(float(np.mean(miss)) if miss else None, 3)} |"
        )
    # mono range error
    out += [
        "",
        "## Perception-driven range error vs ground truth (per run, before contact)",
        "",
        "| scenario | condition | n | mean (m) | MAE (m) | p95 abs (m) |",
        "|---|---|---|---|---|---|",
    ]
    for r in base:
        if r["mode"] == "mono" and r["ego_kmh"] == 30.0 and r["condition"] == "npu_p95":
            e = r["mono_range_err"]
            out.append(
                f"| {r['scenario']} | {r['condition']} | {e['n']} | {f(e['mean_m'])} | {f(e['mae_m'])} | "
                f"{f(e['p95_abs_m'])} |"
            )
    # speed sweep
    sw = defaultdict(dict)
    for r in base:
        if r["condition"] in ("npu_p95", "aeb_off") and r["scenario"] in (
            "static_obstacle",
            "pedestrian_crossing",
            "lead_vehicle_braking",
        ):
            key = "aeb_off" if r["condition"] == "aeb_off" else r["mode"]
            sw[(r["scenario"], r["ego_kmh"])][key] = r
    if sw:
        out += [
            "",
            "## Speed sweep (NPU latency 9.85 ms)",
            "",
            "| scenario | km/h | AEB off | GT-assisted: min gap / brake dist "
            "| perception-driven: min gap / brake dist |",
            "|---|---|---|---|---|",
        ]
        for (s, kmh), d in sorted(sw.items()):

            def g(m, d=d):
                r = d.get(m)
                if r is None:
                    return ""
                if r["collision"]:
                    return "**COLLISION**"
                return f"{f(r['min_gap_m'])} m / {f(r['braking_distance_m'])} m"

            off = d.get("aeb_off")
            out.append(
                f"| {s} | {kmh:.0f} | {'collision' if off and off['collision'] else ('no collision' if off else '')} | "
                f"{g('gt_gated')} | {g('mono')} |"
            )
    # determinism
    rep = [r for r in runs if r.get("tag") == "rep2"]
    if rep:
        out += [
            "",
            "## Repeatability (same configuration run twice)",
            "",
            "| scenario | mode | min gap run 1 / run 2 (m) | first brake t run 1 / run 2 (s) | identical logs |",
            "|---|---|---|---|---|",
        ]
        for r2 in rep:
            r1 = by.get((r2["scenario"], r2["mode"], r2["ego_kmh"], r2["condition"]))
            if not r1:
                continue
            stem = f"{r2['scenario']}__{r2['condition']}__v2__{r2['mode']}__{int(r2['ego_kmh'])}kmh"
            l1 = resolve(f"outputs/scenario_logs/{stem}.jsonl").read_text().splitlines()
            l2 = resolve(f"outputs/scenario_logs/{stem}__rep2.jsonl").read_text().splitlines()
            same = _strip(l1) == _strip(l2)
            out.append(
                f"| {r2['scenario']} | {r2['mode']} | {f(r1['min_gap_m'], 4)} / {f(r2['min_gap_m'], 4)} | "
                f"{f(r1['first_applied_brake_t'])} / {f(r2['first_applied_brake_t'])} | {'yes' if same else 'no'} |"
            )
    resolve("reports/scenario_tables_v3.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote reports/scenario_tables_v3.md ({len(out)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
